import type { Tool } from 'ai';
import type { z } from 'zod';

/**
 * A tool the model may call. This is the AI SDK's `Tool` type; build one from
 * a Zod schema with `defineTool`. Tools are an allowlist: the adapter only
 * ever exposes tools that were registered with it, and a request must name
 * the ones it wants.
 */
export type AITool = Tool;
export type AIToolSet = Record<string, AITool>;

/** What the configured model endpoint can do, declared rather than assumed. */
export type AICapabilities = {
  streaming: boolean;
  structuredOutput: boolean;
  toolCalling: boolean;
};

/** Limits for one request. The adapter's configured values are ceilings. */
export type AIBudget = {
  /** Wall-clock limit for the whole request, including tool calls. */
  timeoutMs: number;
  /** Maximum tokens generated by one model call. */
  maxOutputTokens: number;
  /** Maximum model calls in one request (tool loops). */
  maxSteps: number;
  /** Stop a tool loop once input plus output tokens reach this total. */
  maxTotalTokens: number;
};

export type AIRequestOptions = {
  /** Names of registered tools this request may use. Default: none. */
  tools?: readonly string[];
  /** Lower the limits for this request. Values above the ceiling are clamped. */
  budget?: Partial<AIBudget>;
  /** Cancel the request, for example when the HTTP client disconnects. */
  signal?: AbortSignal;
  /** Instructions kept separate from the user's prompt. */
  system?: string;
};

export type AIOperation = 'generate' | 'stream' | 'generateObject';

export type AIErrorKind =
  | 'invalid_request'
  | 'unsupported'
  | 'timeout'
  | 'aborted'
  | 'budget_exceeded'
  | 'invalid_output'
  | 'provider_error';

export type AIOutcome = 'ok' | AIErrorKind;

/**
 * One line of usage logging. It never contains prompt, response, tool input
 * or tool output text.
 */
export type AIUsageRecord = {
  adapter: string;
  model: string;
  operation: AIOperation;
  outcome: AIOutcome;
  latencyMs: number;
  inputTokens?: number;
  outputTokens?: number;
  steps: number;
  toolCalls: number;
};

export type AIUsageSink = (record: AIUsageRecord) => void;

export interface AIAdapter {
  /** Adapter name, as it appears in usage records. */
  readonly name: string;
  readonly model: string;
  readonly capabilities: Readonly<AICapabilities>;
  /** Names of the tools registered with this adapter (the allowlist). */
  readonly toolNames: readonly string[];
  /** Text answer. With `options.tools`, runs a bounded tool loop first. */
  generate(prompt: string, options?: AIRequestOptions): Promise<string>;
  /** Answer validated against a Zod schema before it is returned. */
  generateObject<S extends z.ZodType>(
    schema: S,
    prompt: string,
    options?: AIRequestOptions,
  ): Promise<z.output<S>>;
  /** Text answer as it is produced. */
  stream(prompt: string, options?: AIRequestOptions): AsyncIterable<string>;
}

/** Errors carry a kind and a fixed message; they never echo the prompt. */
export class AIError extends Error {
  readonly kind: AIErrorKind;

  constructor(kind: AIErrorKind, message: string, options?: ErrorOptions) {
    super(message, options);
    this.name = 'AIError';
    this.kind = kind;
  }
}
